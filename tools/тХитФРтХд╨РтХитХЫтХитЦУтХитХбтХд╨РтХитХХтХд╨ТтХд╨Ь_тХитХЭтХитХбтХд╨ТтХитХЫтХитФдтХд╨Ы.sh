#!/bin/sh
# ВЫЗОВЫ СТАТИЧЕСКИХ МЕТОДОВ У НАШИХ ТИПОВ.
#
# Пробник подменяет LevelView3D и GameBootstrap заглушками, и ошибки внутри них
# проходят насквозь. Проверка вызовов сверяет три пары полей, но не ловит
# обращения по ИМЕНИ ТИПА: SeasonState.ForMode, которого не существует.
#
# Здесь для каждого вызова вида Тип.Метод( проверяется, объявлен ли такой метод
# в файле этого типа.
P="$1/scripts"
echo "Проверка вызовов статических методов:"

for f in "$P/Presentation/Level/LevelView3D.cs" "$P/Bootstrap/GameBootstrap.cs"; do
  [ -f "$f" ] || continue
  code=$(mktemp)
  sed 's://.*::; s:"[^"]*":"":g' "$f" > "$code"
  grep -oE "\b[A-Z][A-Za-z0-9_]{2,}\.[A-Za-z_][A-Za-z0-9_]*\(" "$code" \
    | sed 's/($//; s/(//' | sort -u | while IFS=. read t m; do
      # файл, где объявлен тип
      decl=$(grep -rl "^\(public\|internal\).*\(class\|struct\|record\|enum\) $t\b" "$P" --include=*.cs | head -1)
      [ -z "$decl" ] && continue
      # Объявление ищется по ИМЕНИ со скобкой в любом месте строки: у длинных
      # подписей возвращаемый тип переносится на предыдущую строку, и привязка
      # к началу строки давала ложные срабатывания на
      # GallerySweepPlan, GalleryCrowdingPlan, SamplePath.
      grep -qE "\b$m *\(" "$decl" \
        || echo "  $(basename "$f"): $t.$m — НЕТ такого метода в $(basename "$decl")"
    done
  rm -f "$code"
done
# ---- ВЫЗОВЫ СОБСТВЕННЫХ МЕТОДОВ: ПРОБОВАЛ, ОТВЕРГНУТО ----
#
# Хотел ловить вызовы удалённых методов внутри файла: при удалении старого
# генератора я вырезал TickBoat, PlaceBoatOnStem и RebuildBoatArcTable, а вызовы
# остались — четыре ошибки сборки.
#
# Простым разбором это не отличить от:
#   • местных функций внутри метода;
#   • ДОВОДОВ-ФУНКЦИЙ, переданных в метод: `Func<int,bool> same` вызывается как
#     `same(j)` и выглядит точно так же.
#
# Проверка давала два ложных срабатывания и при этом НЕ ловила подставленный
# настоящий вызов. Молчащая проверка хуже отсутствующей, а кричащая зря — тем
# более: к ней перестают прислушиваться.
#
# Этот класс ошибок остаётся за сборкой в Godot.
echo "готово"
